# backend/models.py - Pydantic Data Models for Sentiment Analysis API
from pydantic import BaseModel, Field
from typing import List, Optional


# ==============================================================================
#                              REQUEST MODELS
# ==============================================================================

class AnalysisRequest(BaseModel):
    """Payload for sentiment and customer voice analysis requests."""
    keyword: Optional[str] = "GTBank"
    limit: Optional[int] = 30
    max_posts: Optional[int] = None
    platforms: Optional[List[str]] = None

    def get_limit(self) -> int:
        """Returns sample size limit, preferring max_posts if provided."""
        return self.max_posts if self.max_posts is not None else (self.limit or 30)

    def get_keyword(self) -> str:
        """Returns target keyword or default brand."""
        return self.keyword or "GTBank"


class CompetitorRequest(BaseModel):
    """Payload for competitor sentiment identification and comparison."""
    keyword: Optional[str] = None
    brand_name: Optional[str] = None
    platforms: Optional[List[str]] = None

    def get_keyword(self) -> str:
        """Returns target brand name."""
        return self.keyword or self.brand_name or "GTBank"


# ==============================================================================
#                          STATISTICS & DATA POINTS
# ==============================================================================

class TweetResponse(BaseModel):
    """Individual social media post with classified sentiment."""
    text: str
    sentiment: str
    confidence: float
    timestamp: str
    category: Optional[str] = None
    emotion: Optional[str] = None
    summary: Optional[str] = None


class VolumeDataPoint(BaseModel):
    """Time-series mention count for trend visualization."""
    date: str
    count: int


class SummaryStats(BaseModel):
    """High-level summary metrics for brand sentiment."""
    total: int
    positive: int
    negative: int
    neutral: int
    sentiment_score: float
    engagement_rate: float
    active_issues: int


# ==============================================================================
#                            COMPETITOR MODELS
# ==============================================================================

class CompetitorData(BaseModel):
    """Sentiment and mention metrics for a single competitor brand."""
    name: str
    sentiment_score: float
    total_mentions: int
    positive_rate: float
    negative_rate: float


class CompetitorTimeData(BaseModel):
    """Time-series comparison scores across competing brands."""
    date: str
    brand: float
    competitor_a: float
    competitor_b: float
    competitor_c: float
    competitor_d: float


class CompetitorResponse(BaseModel):
    """Aggregated response containing competitor scores and time trends."""
    competitors: List[CompetitorData]
    time_comparison: List[CompetitorTimeData]


# ==============================================================================
#                         CUSTOMER VOICE & COMPLAINTS
# ==============================================================================

class AIInsights(BaseModel):
    """Executive AI insights generated by 5-mini."""
    summary: str
    key_themes: List[str]
    recommendation: str


class ComplaintCategory(BaseModel):
    """Categorized customer complaint with occurrence percentage."""
    category: str
    percentage: float
    count: int


class RecentOpinion(BaseModel):
    """Sample opinion snippet with classification confidence."""
    text: str
    sentiment: str
    confidence: float
    category: Optional[str] = None
    emotion: Optional[str] = None


class CustomerVoiceResponse(BaseModel):
    """Breakdown of customer complaints and recent brand opinions."""
    complaint_categories: List[ComplaintCategory]
    recent_opinions: List[RecentOpinion]
    ai_insights: Optional[AIInsights] = None


# ==============================================================================
#                         TOP-LEVEL API RESPONSES
# ==============================================================================

class FullResponse(BaseModel):
    """Standard response model for /analyze_sentiment."""
    summary: SummaryStats
    tweets: List[TweetResponse]
    volume_over_time: List[VolumeDataPoint]
    ai_insights: Optional[AIInsights] = None


class UnifiedAnalysisResponse(BaseModel):
    """Unified response model for /analyze_all containing overview and voice data."""
    summary: SummaryStats
    tweets: List[TweetResponse]
    volume_over_time: List[VolumeDataPoint]
    customer_voice: CustomerVoiceResponse
    ai_insights: Optional[AIInsights] = None
